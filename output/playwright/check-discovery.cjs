const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const base = process.env.DIRECTORY_URL || 'http://127.0.0.1:8124';
const evidence = path.join(process.cwd(), 'output/playwright');
(async () => {
  const browser = await chromium.launch({channel: 'chrome', headless: true});
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}});
  const page = await context.newPage();
  page.setDefaultTimeout(8000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (value, label) => { assert.ok(value, label); console.log('PASS ' + label); };
  const ready = () => page.locator('[data-results-status]').filter({hasText: 'Showing'}).waitFor();
  const screenshot = name => page.screenshot({path:path.join(evidence,name+'.png')});
  try {
    await page.goto(base + '/directory/'); await ready();
    await screenshot('after-desktop');
    check(await page.locator('.discovery-row').count() === 12, 'initial results are bounded to 12');
    await page.getByRole('button',{name:'Show 12 more skills'}).click();
    check(await page.locator('.discovery-row').count() === 24, 'pagination reveals 12 additional skills');
    check(await page.locator('.discovery-row h3 a').nth(12).evaluate(el => document.activeElement === el), 'pagination transfers keyboard focus');
    const q = page.getByRole('searchbox', {name:'Search skills'});
    await q.fill('seo audit'); await q.press('Enter');
    await page.getByRole('combobox',{name:'Quality grade'}).selectOption('B');
    const expected = JSON.parse(fs.readFileSync('docs/directory/search-index.json','utf8')).filter(s => s.grade==='B' && ['seo','audit'].every(t => [s.name,s.repo,s.description,s.label].join(' ').toLowerCase().includes(t)));
    check((await page.locator('[data-results-status]').textContent()).includes('of '+expected.length+' skills'), 'multi-term search and grade intersection');
    check(new URL(page.url()).searchParams.get('grade')==='B', 'filters persist in shareable URL');
    await page.reload(); await ready();
    check(await q.inputValue()==='seo audit' && await page.getByRole('combobox',{name:'Quality grade'}).inputValue()==='B', 'URL restores controls and results');
    await q.fill('zzzz-no-such-skill'); await q.press('Enter');
    check(await page.locator('.search-empty').isVisible(), 'empty state offers recovery');
    await screenshot('after-empty');
    await page.getByRole('button',{name:'Clear all filters'}).click();
    check(await q.evaluate(el => el===document.activeElement), 'reset returns focus to search');
    await page.locator('h1').click(); await page.keyboard.press('Meta+k');
    check(await q.evaluate(el => el===document.activeElement), 'Cmd+K focuses search');
    await q.fill('review'); await q.press('Escape');
    check(await q.inputValue()==='', 'Escape clears search');
    await page.getByRole('combobox',{name:'Category',exact:true}).selectOption('frontend-design');
    await page.getByRole('combobox',{name:'Sort by'}).selectOption('name');
    const names = await page.locator('.discovery-row h3').allTextContents();
    check(names.every((n,i) => !i || names[i-1].localeCompare(n)<=0), 'category and alphabetical sort work together');
    await page.getByRole('combobox',{name:'Quality grade'}).selectOption('B');
    await page.locator('[data-directory-browser]').scrollIntoViewIfNeeded(); await screenshot('after-filtered');
    await page.setViewportSize({width:390,height:844});
    await page.goto(base+'/directory/'); await ready(); await screenshot('after-mobile');
    await page.locator('.category-rail summary').click();
    await page.locator('.category-rail a[data-category="frontend-design"]').click();
    check(await page.locator('[data-result-title]').evaluate(el => el === document.activeElement), 'mobile category selection transfers focus');
    await page.locator('.result-heading').scrollIntoViewIfNeeded(); await screenshot('after-mobile-results');
    for (const width of [320,390,680,768,1024,1440]) {
      await page.setViewportSize({width,height:900});
      check(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth), 'home has no horizontal overflow at '+width);
    }
    await page.goto(base+'/directory/gooseworks-ai/goose-skills/#icp-website-audit');
    await page.locator('#icp-website-audit').waitFor({state:'visible'});
    check(await page.locator('#icp-website-audit').isVisible(), 'search destination reveals row inside collapsed disclosure');
    await page.setViewportSize({width:680,height:900});
    await page.goto(base+'/directory/frontend-design/');
    const cells = await page.locator('.skill-table tbody tr').first().evaluate(row => ({row: row.getBoundingClientRect().width, name:row.querySelector('.name').getBoundingClientRect().width}));
    check(cells.name > cells.row*.8, 'tablet names use full row width');
    const filter = page.getByRole('searchbox', {name:'Filter by name, repository or task'});
    await filter.fill('zzzz-no-such-skill');
    check(await page.locator('[data-table-empty]').isVisible(), 'category empty state');
    await page.getByRole('button',{name:'Clear',exact:true}).click();
    check(await page.locator('.skill-table tbody tr:not([hidden])').count()===JSON.parse(fs.readFileSync('docs/directory/search-index.json','utf8')).filter(s => s.category==='frontend-design').length, 'category clear restores every skill');
    await page.setViewportSize({width:1440,height:1000}); await screenshot('after-category');
    await page.emulateMedia({reducedMotion:'reduce'});
    check(await page.evaluate(() => matchMedia('(prefers-reduced-motion: reduce)').matches), 'reduced motion visit');
    await page.route('**/search-index.json', route => route.abort());
    await page.goto(base+'/directory/');
    await page.locator('[data-search-error]').waitFor({state:'visible'});
    check(await page.locator('.discovery-row').count()===8, 'failed search retains static starter skills');
    await screenshot('after-search-error');
    await page.unroute('**/search-index.json');
    await page.getByRole('button',{name:'Try again'}).click(); await ready();
    check(await page.locator('.discovery-row').count()===12, 'retry recovers search');
    let release;
    const gate = new Promise(resolve => { release=resolve; });
    await page.route('**/search-index.json', async route => { await gate; await route.continue(); });
    await page.goto(base+'/directory/',{waitUntil:'domcontentloaded'});
    await page.locator('.search-loading').waitFor({state:'visible'});
    check(await page.locator('[data-search-results]').getAttribute('aria-busy')==='true', 'loading state exposes busy status');
    await screenshot('after-loading');
    release(); await ready(); await page.unroute('**/search-index.json');
    const nojs = await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
    const fallback = await nojs.newPage();
    await fallback.goto(base+'/directory/');
    check(await fallback.locator('.category-rail a').count()===17 && await fallback.locator('.discovery-row').count()===8, 'no-JavaScript categories and starter skills remain');
    check(!(await fallback.locator('form[role=search]').isVisible()), 'no inert search exposed without JavaScript');
    await nojs.close();
    check(errors.length===0, 'no page JavaScript errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
