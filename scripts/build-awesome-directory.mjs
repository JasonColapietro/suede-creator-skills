const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://skills.suedeai.ai/directory/';
const GENERATED = '<!-- Generated by scripts/build-awesome-directory.mjs. Edit directory data or the generator. -->';
const ISSUE = 'https://github.com/JasonColapietro/suede-creator-skills/issues/new?template=directory-listing.yml';
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'skill';
const repoSlug = (repo) => repo.split('/').map(slugify).join('/');
const repoAnchor = (repo) => repo.split('/').map(slugify).join('--');
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const alphabetical = (a, b) => compare(a.toLowerCase(), b.toLowerCase()) || compare(a, b);
const plain = (s) => String(s).replace(/\s+/g, ' ').trim();
const md = (s) => plain(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/[\\`*_[\]{}|]/g, '\\$&');
const link = (text, url) => `[${md(text)}](${url})`;
const github = (repo) => `https://github.com/${repo}`;
const encodedPath = (p) => p.split('/').map(encodeURIComponent).join('/');
const number = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');

export function excerpt(value) {
  let text = plain(value);
  // Prefer a complete first sentence; otherwise use a visibly shortened excerpt.
  const first = text.match(/^.*?[.!?](?=\s+[A-Z]|$)/)?.[0];
  if (first && first.length <= 240) text = first;
  if ([...text].length > 240) text = [...text].slice(0, 237).join('').replace(/\s+\S*$/, '') + '…';
  return md(text);
}

export function loadInputs(root = ROOT) {
  const bytes = fs.readFileSync(path.join(root, 'directory/skills.json'));
  const read = (name) => JSON.parse(fs.readFileSync(path.join(root, `directory/${name}.json`), 'utf8'));
  // Guides and CTA copy are optional editorial layers; the catalog builds without them.
  const optional = (name, fallback) => fs.existsSync(path.join(root, `directory/${name}.json`)) ? read(name) : fallback;
  const guides = optional('editorial/pages', { pages: [] });
  for (const g of guides.pages) {
    if (!/^[a-z0-9-]+$/.test(g.id) || !['draft', 'published'].includes(g.status)) throw new Error(`Invalid guide: ${g.id}`);
    if (!/^directory\/guides\/[a-z0-9-]+\/$/.test(g.path)) throw new Error(`Invalid guide path: ${g.id}`);
    if (!/^directory\/editorial\/[a-z0-9-]+\.md$/.test(g.source) || !fs.existsSync(path.join(root, g.source))) throw new Error(`Missing guide source: ${g.id}`);
  }
  return {
    data: JSON.parse(bytes), sha256: createHash('sha256').update(bytes).digest('hex'),
    categories: read('categories'), inclusions: read('inclusions'), exclusions: read('exclusions'),
    // One CTA source for the site and this catalog: directory/services-cta.json.
    editorial: read('featured-projects'), guides, ctas: optional('services-cta', { campaigns: [], lead_by_category: {} }),
  };
}

function validate({ data, categories, inclusions, exclusions, editorial }) {
  if (data.score_method !== SCORE_METHOD || data.checks.map((c) => c.id).join() !== CHECK_IDS.join()) throw new Error('Unsupported score method');
  if (!/^\d{4}-\d{2}-\d{2}$/.test(data.generated) || !/^[a-f0-9]{32}$/.test(data.snapshot_id)) throw new Error('Invalid snapshot metadata');
  const categoryIds = new Set();
  for (const c of categories) {
    if (!/^[a-z0-9-]+$/.test(c.slug) || categoryIds.has(c.slug)) throw new Error(`Invalid or duplicate category: ${c.slug}`);
    categoryIds.add(c.slug);
  }
  const scopes = new Map(Object.entries(inclusions.skills || {}).map(([repo, names]) => [repo.toLowerCase(), new Set(names)]));
  const key = (e) => (typeof e === 'string' ? e : e.id).toLowerCase();
  const excludedRepos = new Set((exclusions.repositories || []).map(key));
  const excludedSkills = new Set((exclusions.skills || []).map(key));
  const ids = new Set(), targets = new Set(), names = new Set(), repoAnchors = new Map();
  for (const s of data.skills) {
    const repo = data.repos[s.repo], id = `${s.repo}/${s.slug}`;
    if (!repo || !/^[\w.-]+\/[\w.-]+$/.test(s.repo) || !/^[a-z0-9-]+$/.test(s.slug)) throw new Error(`Invalid source: ${id}`);
    if (!s.description || !s.name || !repo.branch || !s.dir || s.dir.split('/').some((p) => p === '..' || p === '')) throw new Error(`Missing source metadata: ${id}`);
    if (!categoryIds.has(s.category)) throw new Error(`Unknown category: ${id}`);
    if (scopes.has(s.repo.toLowerCase()) && !scopes.get(s.repo.toLowerCase()).has(s.name)) throw new Error(`Outside accepted scope: ${id}`);
    if (excludedRepos.has(s.repo.toLowerCase()) || excludedSkills.has(`${s.repo}/${s.name}`.toLowerCase())) throw new Error(`Record is excluded: ${id}`);
    if (!listed(s)) throw new Error(`Invalid listing eligibility: ${id}`);
    if (s.score !== qualityScore(s, repo, data.generated) || s.grade !== letterGrade(s.score)) throw new Error(`Inconsistent score: ${id}`);
    if (s.security_scan_status !== 'not_scanned') throw new Error(`Unsupported security claim: ${id}`);
    const target = listingTarget(s), name = `${s.repo}/${s.name}`.toLowerCase();
    if (ids.has(id.toLowerCase()) || targets.has(target) || names.has(name)) throw new Error(`Duplicate listing: ${id}`);
    ids.add(id.toLowerCase()); targets.add(target); names.add(name);
    const anchor = repoAnchor(s.repo);
    if (repoAnchors.has(anchor) && repoAnchors.get(anchor) !== s.repo) throw new Error(`Duplicate publisher anchor: ${s.repo}`);
    repoAnchors.set(anchor, s.repo);
  }
  const projects = new Set();
  for (const member of directoryMembers(editorial)) {
    if (excludedRepos.has(member.repo.toLowerCase()) || member.skills.some((skill) => excludedSkills.has(`${member.repo}/${skill.id}`.toLowerCase()))) throw new Error(`Directory member is excluded: ${member.repo}`);
  }
  for (const p of editorial.projects) {
    if (!/^[a-z0-9-]+$/.test(p.id) || projects.has(p.id) || !/^[a-f0-9]{40}$/.test(p.commit)) throw new Error('Invalid featured project evidence');
    projects.add(p.id);
    if (excludedRepos.has(p.repo.toLowerCase())) throw new Error(`Featured project is excluded: ${p.repo}`);
    for (const skill of p.skills || []) {
      if (!data.skills.some((s) => s.repo === p.repo && s.slug === skill.id)) throw new Error(`Featured skill outside accepted scope: ${p.repo}/${skill.id}`);
    }
  }
}

