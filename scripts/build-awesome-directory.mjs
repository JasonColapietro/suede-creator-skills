// Own only generated Markdown; preserve hand-written contribution guidance.
export function syncCatalog(outRoot, pages, checkOnly = false) {
  const stale = [];
  for (const [name, body] of pages) {
    const target = path.join(outRoot, name);
    if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === body) continue;
    stale.push(name);
    if (!checkOnly) {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, body);
    }
  }
  function scan(dir) {
    if (!fs.existsSync(dir)) return;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const target = path.join(dir, entry.name);
      if (entry.isDirectory()) { scan(target); continue; }
      const name = path.relative(outRoot, target).split(path.sep).join('/');
      if (!entry.isFile() || !name.endsWith('.md') || pages.has(name)) continue;
      if (!fs.readFileSync(target, 'utf8').startsWith(GENERATED)) continue;
      stale.push(name);
      if (!checkOnly) fs.unlinkSync(target);
    }
  }
  scan(outRoot);
  return stale;
}

