#!/usr/bin/env node
// Writes the "Related skills" section on every skill page under docs/skills/.
//
// The skill pages are the spokes of the /skills/ hub, and before this script
// 48 of them linked to no other skill page at all: a reader (or a crawler)
// who landed on one could only go back up to the catalog. Each page now links
// the pack skills its own SKILL.md names, then the skills whose SKILL.md names
// it, then skills from the same catalog category, so every spoke links its
// neighbours and the links follow the routing the skills already describe.
//
// Pages that carry a hand-written <h2>Related skills</h2> keep it untouched.
// Generated sections sit between related-skills markers and are rewritten in
// place, so the script is idempotent.
//
// Usage:
//   node scripts/build-related-skills.mjs          # write docs/skills/*.html
//   node scripts/build-related-skills.mjs --check  # exit 1 if a page would change

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const MAX_RELATED = 5;
export const MIN_RELATED = 3;
const START = "<!-- related-skills:start (generated by scripts/build-related-skills.mjs) -->";
const END = "<!-- related-skills:end -->";
const BLOCK_RE = /[ \t]*<!-- related-skills:start[^>]*-->[\s\S]*?<!-- related-skills:end -->\n?/;
const HAND_WRITTEN_RE = /<h2[^>]*>\s*Related skills\s*<\/h2>/i;

const pick = (html, re) => (html.match(re) || [])[1] || "";

export function loadSkills(root = repoRoot) {
  const sRoot = path.join(root, "skills");
  const pRoot = path.join(root, "docs", "skills");
  const skills = new Map();
  for (const name of fs.readdirSync(sRoot).sort()) {
    const skillMd = path.join(sRoot, name, "SKILL.md");
    const page = path.join(pRoot, `${name}.html`);
    if (!fs.existsSync(skillMd) || !fs.existsSync(page)) continue;
    const html = fs.readFileSync(page, "utf8");
    if (/<meta[^>]+name="robots"[^>]+noindex/i.test(html)) continue;
    skills.set(name, {
      name,
      page,
      source: fs.readFileSync(skillMd, "utf8"),
      html,
      label: pick(html, /<span class="h1-task">([\s\S]*?)<\/span>/).trim() || name,
      description: pick(html, /<meta name="description" content="([^"]*)"/).trim(),
      category: pick(html, /<div class="eyebrow">[^<]*?&middot;\s*([^<]*?)\s*<\/div>/).trim(),
    });
  }
  return skills;
}

// Pack skill names a SKILL.md mentions, in order of first mention.
function mentions(source, self, names) {
  const found = [];
  const re = /(?<![a-z0-9-])([a-z0-9]+(?:-[a-z0-9]+)+)(?![a-z0-9-])/g;
  for (const m of source.matchAll(re)) {
    const n = m[1];
    if (n !== self && names.has(n) && !found.includes(n)) found.push(n);
  }
  return found;
}

export function computeRelated(skills) {
  const names = new Set(skills.keys());
  const out = new Map();
  const mentioned = new Map([...skills].map(([n, s]) => [n, mentions(s.source, n, names)]));
  for (const [name, s] of skills) {
    const list = [...mentioned.get(name)];
    const add = (n) => { if (n !== name && !list.includes(n)) list.push(n); };
    // Skills whose own SKILL.md routes to this one.
    for (const [other, refs] of mentioned) if (refs.includes(name)) add(other);
    // Top up from the same catalog category.
    if (list.length < MIN_RELATED && s.category) {
      for (const [other, o] of skills) if (o.category === s.category) add(other);
    }
    out.set(name, list.slice(0, MAX_RELATED));
  }
  return out;
}

export function renderSection(related, skills) {
  const items = related.map((n) => {
    const t = skills.get(n);
    const desc = t.description ? `: ${t.description}` : "";
    return `          <li><a href="${n}.html">${t.label}</a>${desc}</li>`;
  });
  return `      ${START}
      <section aria-labelledby="related-skills-title">
        <h2 id="related-skills-title">Related skills</h2>
        <ul>
${items.join("\n")}
        </ul>
      </section>
      ${END}
`;
}

export function renderPage(html, section) {
  if (BLOCK_RE.test(html)) return html.replace(BLOCK_RE, section);
  if (HAND_WRITTEN_RE.test(html)) return html;
  // Insert at the start of the install block's line, or failing that </main>'s.
  const anchor = html.match(/^[ \t]*<section class="install-block"/m) || html.match(/^[ \t]*<\/main>/m);
  if (!anchor) throw new Error("skill page has neither an install block nor a </main>");
  return html.slice(0, anchor.index) + section + html.slice(anchor.index);
}

function run() {
  const check = process.argv.includes("--check");
  const skills = loadSkills();
  const related = computeRelated(skills);
  const stale = [];
  for (const [name, s] of skills) {
    const next = renderPage(s.html, renderSection(related.get(name), skills));
    if (next === s.html) continue;
    stale.push(name);
    if (!check) fs.writeFileSync(s.page, next);
  }
  if (check && stale.length) {
    console.error(`Related-skills sections are stale on ${stale.length} page(s): ${stale.join(", ")}`);
    console.error("Run: node scripts/build-related-skills.mjs");
    process.exit(1);
  }
  console.log(check ? `docs/skills related sections are up to date (${skills.size} pages).` : `Wrote related sections on ${stale.length} of ${skills.size} pages.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) run();
