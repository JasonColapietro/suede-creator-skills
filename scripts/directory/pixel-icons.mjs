const PATHS = new Map();
for (const [name, rows] of Object.entries(BITMAPS)) {
  if (rows.length !== 12 || rows.some((r) => !/^[#.]{12}$/.test(r))) throw new Error(`pixel icon ${name} is not a 12 by 12 bitmap`);
  const d = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < 12) {
      if (row[x] !== "#") { x++; continue; }
      let w = 1;
      while (x + w < 12 && row[x + w] === "#") w++;
      d.push(`M${x} ${y}h${w}v1h-${w}z`);
      x += w;
    }
  });
  PATHS.set(name, d.join(""));
}

export const ICON_NAMES = [...PATHS.keys()];

export function pixelIcon(name, { size = 24, className = "pix", label = null } = {}) {
  const d = PATHS.get(name);
  if (!d) throw new Error(`unknown pixel icon ${name}`);
  const a11y = label ? ` role="img" aria-label="${label.replace(/"/g, "&quot;")}"` : ' aria-hidden="true"';
  return `<svg class="${className}" viewBox="0 0 12 12" width="${size}" height="${size}" shape-rendering="crispEdges"${a11y}><path fill="currentColor" d="${d}"/></svg>`;
}

// A dot matrix: one square per item, in the order given, colored by the
// class its record maps to. Used for the skill matrices on the hub, the
// category pages and the trust page. Returns a standalone SVG document.
export function dotMatrix(items, { cols = 96, cell = 10, dot = 8, colorOf, title, legend = [] }) {
  const rows = Math.ceil(items.length / cols);
  const w = cols * cell;
  const h = rows * cell;
  // One path per color keeps the file small: a dot is "M x y h d v d h -d z".
  const byColor = new Map();
  items.forEach((item, i) => {
    const x = (i % cols) * cell;
    const y = Math.floor(i / cols) * cell;
    const color = colorOf(item);
    byColor.set(color, `${byColor.get(color) || ""}M${x} ${y}h${dot}v${dot}h-${dot}z`);
  });
  const paths = [...byColor].map(([color, d]) => `<path fill="${color}" d="${d}"/>`);
  const legendText = legend.length ? `<desc>${legend.map(([c, l]) => `${l}: ${c}`).join("; ")}</desc>` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" shape-rendering="crispEdges" role="img" aria-labelledby="t"><title id="t">${title}</title>${legendText}${paths.join("")}</svg>\n`;
}
