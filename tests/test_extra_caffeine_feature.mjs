import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { qualityScore } from '../scripts/directory/badges.mjs';
import { execFileSync, spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const read = (p) => fs.readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
const repo = 'cwong5/extra-caffeine-mcp';
const id = 'extra-caffeine-workflow';

test('Extra Caffeine publishes the accepted source with its computed report and listing badge', () => {
  const data = JSON.parse(read('directory/skills.json'));
  const records = data.skills.filter((s) => s.repo === repo);
  assert.equal(records.length, 1, 'ingest the one accepted workflow');
  const [record] = records;
  const receipt = JSON.parse(read('directory/intake/extra-caffeine-2026-10-26.json'));
  assert.equal(receipt.reviewed_at, '2026-10-26');
  assert.equal(receipt.base_snapshot_date, data.generated);
  assert.equal(data.repos[repo].commit_sha, receipt.revision);
  assert.equal(data.repos[repo].scoped_install, true);
  assert.equal(record.checks, '11110111');
  assert.equal(record.score, 69);
  assert.equal(record.score, qualityScore(record, data.repos[repo], data.generated));
  assert.equal(record.grade, 'D');
  assert.equal(record.security_scan_status, 'not_scanned');
  assert.equal(record.license, 'All rights reserved');
  assert.equal(record.open_license, false);
  assert.equal(record.featured, undefined, '6/7 does not receive a full skill page');
  assert.deepEqual(record.size, receipt.assessments[0].size);
  const others = { repos: Object.fromEntries(Object.entries(data.repos).filter(([key]) => key !== repo)), skills: data.skills.filter((s) => s.repo !== repo) };
  assert.equal(createHash('sha256').update(JSON.stringify(others)).digest('hex'), receipt.unchanged_catalog_sha256, 'preserve all other listing records and repository facts');
  const folder = `docs/directory/${repo}/${id}/`;
  const report = JSON.parse(read(folder + 'report.json'));
  assert.equal(report.source.revision, receipt.revision);
  assert.equal(report.quality.score, 69);
  assert.equal(report.quality.grade, 'D');
  assert.deepEqual(report.badges.map((b) => b.kind), ['listing']);
  assert.equal(report.listing_url, `https://skills.suedeai.ai/directory/${repo}/#${id}`);
  for (const badge of ['badge.svg', 'score.svg']) assert.doesNotMatch(read(folder + badge), /Suede Certified|Grade B|86 \/ 100/);
  const listing = read(`docs/directory/${repo}/index.html`);
  assert.ok(listing.includes(`id="${id}"`));
  assert.ok(listing.includes(`${id}/report.json`));
  assert.doesNotMatch(listing, /<code[^>]*>npx skills add|<code[^>]*>git clone|<code[^>]*>cp -R/);
  const project = JSON.parse(read('directory/featured-projects.json')).projects.find((p) => p.id === 'extra-caffeine');
  assert.ok(project);
  assert.deepEqual(project.skills.map((s) => s.id), [id]);
  assert.equal(project.capabilities, undefined);
  assert.equal(project.commit, '4e0ac32e685c5366ab487502173168470a42a178');
  assert.equal(project.workflow_url, `https://github.com/${repo}/blob/${project.commit}/skills/${id}/SKILL.md`);
  assert.deepEqual(JSON.parse(read('directory/inclusions.json')).skills[repo], [id]);
  assert.ok(!fs.existsSync(new URL(`../skills/${id}`, import.meta.url)), 'no proprietary files in MIT pack');
  const page = read('docs/directory/featured/index.html');
  const feature = page.split('id="extra-caffeine"')[1]?.split('</article>')[0];
  assert.ok(feature);
  assert.ok(feature.includes(`href="${project.workflow_url}"`));
  for (const fact of ['macOS 14+', 'Extra Caffeine 1.2+', 'paid', 'All rights reserved']) assert.ok(feature.includes(fact), fact);
  assert.ok(feature.includes(`href="../${repo}/#${id}"`), 'feature links to the scored listing');
  assert.doesNotMatch(feature, /editorial|catalog listing is pending/i);
  assert.doesNotMatch(feature, /npx skills add|git clone|cp -R|security certified|score\.svg/);
  assert.ok(page.includes('https://skills.suedeai.ai/directory/featured/#extra-caffeine'));
  assert.ok(page.includes('https://skills.suedeai.ai/directory/badges/featured.svg'));
});

test('restricted full pages accept publisher setup links without install commands', (t) => {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'extra-caffeine-setup-'));
  t.after(() => fs.rmSync(temp, { recursive: true, force: true }));
  const fixture = path.join(temp, 'checkout');
  execFileSync('git', ['clone', '--quiet', '--local', '--no-hardlinks', root, fixture]);
  // Use the working builder so the test verifies an uncommitted fix too.
  fs.copyFileSync(path.join(root, 'scripts/build-directory.mjs'), path.join(fixture, 'scripts/build-directory.mjs'));
  fs.copyFileSync(path.join(root, 'scripts/directory/featured.mjs'), path.join(fixture, 'scripts/directory/featured.mjs'));
  fs.symlinkSync(path.join(root, 'node_modules'), path.join(fixture, 'node_modules'), 'dir');
  const notesPath = path.join(fixture, 'directory/notes.json');
  const notes = JSON.parse(fs.readFileSync(notesPath, 'utf8'));
  // A real, already-qualified restricted page exercises the same route that
  // Extra Caffeine will need after upstream accepts its metadata fix.
  delete notes['anthropics/skills/docx'].commands;
  fs.writeFileSync(notesPath, JSON.stringify(notes));
  const build = spawnSync(process.execPath, [path.join(fixture, 'scripts/build-directory.mjs')], { cwd: fixture, encoding: 'utf8' });
  assert.equal(build.status, 0, build.stderr);
  const page = fs.readFileSync(path.join(fixture, 'docs/directory/anthropics/skills/docx/index.html'), 'utf8');
  const setup = page.split('id="install-title"')[1].split('</section>')[0];
  assert.ok(setup.includes(notes['anthropics/skills/docx'].source));
  assert.doesNotMatch(setup, /id="install-publisher"|npx skills add|git clone/);
});
